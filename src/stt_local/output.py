from __future__ import annotations

import threading
import time
from collections.abc import Callable
from typing import Any


def _keyboard_factory() -> Any:
    from pynput import keyboard

    return keyboard.Controller()


def _command_key() -> Any:
    from pynput import keyboard

    return keyboard.Key.cmd


def _enter_key() -> Any:
    from pynput import keyboard

    return keyboard.Key.enter


def _daemon_timer(delay: float, callback: Callable[[], None]) -> threading.Timer:
    timer = threading.Timer(delay, callback)
    timer.daemon = True
    timer.start()
    return timer


def _is_main_thread() -> bool:
    import Foundation

    return bool(Foundation.NSThread.isMainThread())


def _schedule_on_main(callback: Callable[[], None]) -> None:
    from PyObjCTools import AppHelper

    AppHelper.callAfter(callback)


def call_on_main_thread(
    callback: Callable[[], None],
    *,
    is_main: Callable[[], bool] = _is_main_thread,
    schedule: Callable[[Callable[[], None]], None] = _schedule_on_main,
    timeout: float = 5.0,
) -> None:
    """Run callback on the main thread and wait for it, re-raising its error."""
    if is_main():
        callback()
        return
    done = threading.Event()
    failure: list[BaseException] = []

    def run() -> None:
        try:
            callback()
        except BaseException as exc:
            failure.append(exc)
        finally:
            done.set()

    schedule(run)
    if not done.wait(timeout):
        raise TimeoutError("Main thread did not run the paste in time")
    if failure:
        raise failure[0]


# nspasteboard.org markers: clipboard managers such as Alfred, Maccy and
# Raycast leave items carrying them out of their history.
TRANSIENT_TYPE = "org.nspasteboard.TransientType"
AUTO_GENERATED_TYPE = "org.nspasteboard.AutoGeneratedType"
STRING_TYPE = "public.utf8-plain-text"
# Long enough for the target app to read the pasteboard after Command-V.
RESTORE_DELAY_SECONDS = 0.5

PasteboardItems = list[dict[str, Any]]


class MacPasteboard:
    """The general pasteboard, read and written item by item with every type.
    Call it on the main thread."""

    def __init__(self) -> None:
        import AppKit

        self._appkit = AppKit
        self._pasteboard = AppKit.NSPasteboard.generalPasteboard()

    @property
    def change_count(self) -> int:
        return int(self._pasteboard.changeCount())

    def snapshot(self) -> PasteboardItems:
        items: PasteboardItems = []
        for item in self._pasteboard.pasteboardItems() or []:
            data = {}
            for kind in item.types():
                value = item.dataForType_(kind)
                if value is not None:
                    data[str(kind)] = value
            if data:
                items.append(data)
        return items

    def write(self, items: PasteboardItems) -> None:
        import Foundation

        self._pasteboard.clearContents()
        if not items:
            return
        objects = []
        for data in items:
            item = self._appkit.NSPasteboardItem.alloc().init()
            for kind, value in data.items():
                if isinstance(value, bytes):
                    value = Foundation.NSData.dataWithBytes_length_(value, len(value))
                item.setData_forType_(value, kind)
            objects.append(item)
        if not self._pasteboard.writeObjects_(objects):
            raise RuntimeError("Could not write to the clipboard")


def _transient(items: PasteboardItems) -> PasteboardItems:
    if not items:
        return items
    first = {**items[0], TRANSIENT_TYPE: b"", AUTO_GENERATED_TYPE: b""}
    return [first, *items[1:]]


class MacOutput:
    """Pastes text through the clipboard without leaving it there: the
    transcript is marked transient and the previous contents come back."""

    def __init__(
        self,
        *,
        pasteboard_factory: Callable[[], Any] = MacPasteboard,
        keyboard_factory: Callable[[], Any] = _keyboard_factory,
        command_key: Any = None,
        enter_key: Any = None,
        sleep: Callable[[float], None] = time.sleep,
        on_main: Callable[[Callable[[], None]], None] = lambda callback: callback(),
        timer_factory: Callable[[float, Callable[[], None]], Any] | None = None,
        restore_delay: float = RESTORE_DELAY_SECONDS,
    ) -> None:
        self._pasteboard_factory = pasteboard_factory
        self._pasteboard: Any | None = None
        self._keyboard_factory = keyboard_factory
        self._command_key = command_key
        self._enter_key = enter_key
        self._sleep = sleep
        self._on_main = on_main
        self._timer_factory = timer_factory or _daemon_timer
        self._restore_delay = restore_delay
        # Touched only on the main thread.
        self._saved: PasteboardItems | None = None
        self._written_count: int | None = None
        self._restore_token: object | None = None
        self._restore_timer: Any | None = None

    def send(self, text: str, *, press_enter: bool = False) -> None:
        # pynput reads the keyboard layout through Text Input Sources, which
        # macOS only allows on the main thread; elsewhere it aborts the app.
        # The pasteboard work stays there too so the restore can't interleave.
        self._on_main(lambda: self._copy(text))
        try:
            self._sleep(0.05)
            self._on_main(lambda: self._type_paste(press_enter))
        finally:
            self._on_main(self._schedule_restore)

    def _board(self) -> Any:
        if self._pasteboard is None:
            self._pasteboard = self._pasteboard_factory()
        return self._pasteboard

    def _copy(self, text: str) -> None:
        board = self._board()
        self._cancel_restore()
        if self._saved is None:
            # A paste still waiting to restore keeps the user's older contents.
            self._saved = board.snapshot()
        try:
            board.write(_transient([{STRING_TYPE: text.encode()}]))
        except Exception:
            saved, self._saved = self._saved, None
            board.write(saved)
            raise
        self._written_count = board.change_count

    def _cancel_restore(self) -> None:
        self._restore_token = None
        if self._restore_timer is not None:
            self._restore_timer.cancel()
            self._restore_timer = None

    def _schedule_restore(self) -> None:
        token = object()
        self._restore_token = token

        def fire() -> None:
            try:
                self._on_main(lambda: self._restore(token))
            except Exception:
                pass

        self._restore_timer = self._timer_factory(self._restore_delay, fire)

    def _restore(self, token: object) -> None:
        if token is not self._restore_token:
            return
        self._restore_token = None
        self._restore_timer = None
        saved, self._saved = self._saved, None
        board = self._board()
        # Something copied since the paste wins over the old contents.
        if saved is None or board.change_count != self._written_count:
            return
        # Marked transient as well: it is already in the history.
        board.write(_transient(saved))

    def _type_paste(self, press_enter: bool) -> None:
        keyboard = self._keyboard_factory()
        command_key = self._command_key if self._command_key is not None else _command_key()
        with keyboard.pressed(command_key):
            keyboard.tap("v")
        if press_enter:
            self._sleep(0.05)
            enter_key = self._enter_key if self._enter_key is not None else _enter_key()
            keyboard.tap(enter_key)
